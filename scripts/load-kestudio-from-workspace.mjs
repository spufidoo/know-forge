/**
 * One-shot: map know-forge interview exports + seed into KESTUDIO Db2 DDL inserts.
 * Does not modify schema. Writes SQL to db/load-kestudio-data.sql
 * ID columns are DISTINCT TYPE UUID (BINARY(16)) — emit CAST(BX'<32-hex>' AS UUID).
 */
import crypto from "node:crypto"
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(__dirname, "..")
const WS = "00000000-0000-4000-8000-000000000001"
const now = "CURRENT TIMESTAMP"
const UUID_RE =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i

function uuidFrom(seed) {
  const h = crypto.createHash("sha1").update(String(seed)).digest("hex")
  return [
    h.slice(0, 8),
    h.slice(8, 12),
    `5${h.slice(13, 16)}`,
    `${((parseInt(h[16], 16) & 0x3) | 0x8).toString(16)}${h.slice(17, 20)}`,
    h.slice(20, 32),
  ].join("-")
}

function asId(raw, fallbackSeed) {
  const s = String(raw || "").trim()
  if (UUID_RE.test(s)) {
    return s.toLowerCase()
  }
  return uuidFrom(fallbackSeed || s || crypto.randomUUID())
}

/** Db2 UUID literal for DISTINCT TYPE UUID AS BINARY(16). */
function uuidLit(v) {
  if (v == null || v === "NULL") return "NULL"
  const s = String(v).trim().toLowerCase()
  if (!UUID_RE.test(s)) {
    throw new Error(`Invalid UUID for Db2 literal: ${v}`)
  }
  return `CAST(BX'${s.replace(/-/g, "").toUpperCase()}' AS UUID)`
}

function esc(s) {
  return String(s ?? "")
    .replace(/\u0000/g, "")
    .replace(/'/g, "''")
}

function jsonClob(v) {
  return `'${esc(JSON.stringify(v ?? []))}'`
}

function str(v, max) {
  let t = String(v ?? "")
  if (max && t.length > max) t = t.slice(0, max)
  return `'${esc(t)}'`
}

const sql = []
const report = { packs: [], mappingIssues: [] }

sql.push("-- Generated by scripts/load-kestudio-from-workspace.mjs")
sql.push("-- Target: KESTUDIO")
sql.push("")

function insertPack(pack) {
  sql.push(`INSERT INTO knowledge_packs (
  id, workspace_id, name, domain, purpose, audience, primary_session_id, created_at, updated_at
) VALUES (
  ${uuidLit(pack.id)}, ${uuidLit(WS)}, ${str(pack.name, 256)}, ${str(pack.domain, 512)},
  ${str(pack.purpose, 4000)}, ${str(pack.audience, 1024)}, NULL, ${now}, ${now}
);`)
}

function insertSession(s) {
  sql.push(`INSERT INTO interview_sessions (
  id, pack_id, title, expert_name, status, mime_type, duration_ms, has_audio,
  audio_uri, transcript_uri, transcript, created_at, updated_at
) VALUES (
  ${uuidLit(s.id)}, ${uuidLit(s.packId)}, ${str(s.title, 256)}, ${str(s.expertName, 256)},
  ${str(s.status || "analyzed", 32)}, ${str(s.mimeType || "", 128)}, ${Number(s.durationMs) || 0},
  ${s.hasAudio ? 1 : 0},
  ${s.audioUri ? str(s.audioUri, 1024) : "NULL"},
  ${s.transcriptUri ? str(s.transcriptUri, 1024) : "NULL"},
  ${str(s.transcript || "", 1000000)},
  ${now}, ${now}
);`)
}

function insertMedia(sessionId, kind, uri, mime) {
  sql.push(`INSERT INTO media_assets (
  id, session_id, kind, uri, mime_type, byte_size, checksum_sha256, created_at
) VALUES (
  ${uuidLit(uuidFrom(`${sessionId}:${kind}`))}, ${uuidLit(sessionId)}, ${str(kind, 32)},
  ${str(uri, 1024)}, ${str(mime || "", 128)}, NULL, NULL, ${now}
);`)
}

function applyCandidates(packId, sessionId, candidates) {
  for (const c of candidates || []) {
    const candId = asId(c.id, `cand:${packId}:${c.kind}:${c.title}`)
    if (c.id && candId !== String(c.id).toLowerCase()) {
      report.mappingIssues.push(
        `Candidate id "${c.id}" is not a UUID — stored as ${candId}`,
      )
    }
    const p = c.payload || {}
    let acceptedHeuristic = "NULL"
    let acceptedProcedure = "NULL"
    let acceptedGotcha = "NULL"
    let acceptedTerm = "NULL"
    const entryId = uuidFrom(`entry:${candId}`)
    const source = String(p.source || "Interview recording")
    const status = c.status || "pending"

    if (status === "accepted") {
      if (c.kind === "heuristic") {
        sql.push(`INSERT INTO heuristics (
  id, pack_id, title, when_clause, then_clause, because, unless_json, confidence,
  tags_json, source, source_session_id, created_at, updated_at
) VALUES (
  ${uuidLit(entryId)}, ${uuidLit(packId)}, ${str(p.title || c.title, 256)},
  ${str(p.when || "", 4000)}, ${str(p.then || "", 4000)}, ${str(p.because || "", 4000)},
  ${jsonClob(p.unless || [])}, ${str(c.confidence || "medium", 16)},
  ${jsonClob(["interview"])}, ${str(source, 512)}, ${uuidLit(sessionId)}, ${now}, ${now}
);`)
        acceptedHeuristic = uuidLit(entryId)
      } else if (c.kind === "procedure") {
        sql.push(`INSERT INTO procedures (
  id, pack_id, title, goal, when_to_use, when_not_to_use, tags_json, source,
  source_session_id, created_at, updated_at
) VALUES (
  ${uuidLit(entryId)}, ${uuidLit(packId)}, ${str(p.title || c.title, 256)},
  ${str(p.goal || "", 4000)}, ${str(p.whenToUse || "", 4000)}, ${str(p.whenNotToUse || "", 4000)},
  ${jsonClob(["interview"])}, ${str(source, 512)}, ${uuidLit(sessionId)}, ${now}, ${now}
);`)
        const steps = String(p.steps || "")
          .split(/\n/)
          .map((x) => x.trim())
          .filter(Boolean)
        steps.forEach((action, i) => {
          sql.push(`INSERT INTO procedure_steps (
  id, procedure_id, position, action, check_text, note
) VALUES (
  ${uuidLit(uuidFrom(`${entryId}:step:${i}`))}, ${uuidLit(entryId)}, ${i},
  ${str(action, 4000)}, '', ''
);`)
        })
        acceptedProcedure = uuidLit(entryId)
      } else if (c.kind === "gotcha") {
        sql.push(`INSERT INTO gotchas (
  id, pack_id, title, symptom, cause, fix, prevention, tags_json, source,
  source_session_id, created_at, updated_at
) VALUES (
  ${uuidLit(entryId)}, ${uuidLit(packId)}, ${str(p.title || c.title, 256)},
  ${str(p.symptom || "", 4000)}, ${str(p.cause || "", 4000)}, ${str(p.fix || "", 4000)},
  ${str(p.prevention || "", 4000)}, ${jsonClob(["interview"])}, ${str(source, 512)},
  ${uuidLit(sessionId)}, ${now}, ${now}
);`)
        acceptedGotcha = uuidLit(entryId)
      } else if (c.kind === "term") {
        sql.push(`INSERT INTO glossary_terms (
  id, pack_id, term, definition, aliases_json, related_json, source,
  source_session_id, created_at, updated_at
) VALUES (
  ${uuidLit(entryId)}, ${uuidLit(packId)}, ${str(p.term || c.title, 256)},
  ${str(p.definition || "", 4000)}, ${jsonClob(p.aliases || [])}, ${jsonClob(p.related || [])},
  ${str(source, 512)}, ${uuidLit(sessionId)}, ${now}, ${now}
);`)
        acceptedTerm = uuidLit(entryId)
      }
    }

    sql.push(`INSERT INTO analysis_candidates (
  id, session_id, kind, title, excerpt, confidence, status, payload_json,
  accepted_heuristic_id, accepted_procedure_id, accepted_gotcha_id, accepted_term_id,
  created_at, updated_at
) VALUES (
  ${uuidLit(candId)}, ${uuidLit(sessionId)}, ${str(c.kind, 16)}, ${str(c.title, 256)},
  ${str(c.excerpt || "", 4000)}, ${str(c.confidence || "medium", 16)}, ${str(status, 16)},
  ${jsonClob(p)},
  ${acceptedHeuristic}, ${acceptedProcedure}, ${acceptedGotcha}, ${acceptedTerm},
  ${now}, ${now}
);`)
  }
}

function setPrimarySession(packId, sessionId) {
  sql.push(
    `UPDATE knowledge_packs SET primary_session_id = ${uuidLit(sessionId)}, updated_at = ${now} WHERE id = ${uuidLit(packId)};`,
  )
}

